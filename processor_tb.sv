// current single-cycle tpross: arithmetic, branches, LW/SW, jumps and reset.
// set the defparam path below if the simulator runs outside the repo root.
module processor_tb;

logic clk = 1'b0;
logic reset = 1'b1;
integer passed = 0;

tpross dut (.clk(clk), .reset(reset));
defparam dut.iminstance.MEMFILE = "IM/program.hex";

function automatic logic [31:0] memory_seed(input integer index);
    memory_seed = 32'h11223344 + index;
endfunction

task automatic tick;
    clk = 1'b0;
    #5;
    clk = 1'b1;
    #1;
    clk = 1'b0;
    #4;
endtask

task automatic prepare(
    input logic [31:0] instruction,
    input logic [31:0] value1,
    input logic [31:0] value2,
    input integer initial_pc = 0
);
    reset = 1'b1;
    for (integer n = 0; n < 256; n++) begin
        dut.iminstance.memory[n] = 32'h00000013;
        dut.dminstance.memory[n] = memory_seed(n);
    end
    tick();
    reset = 1'b0;
    for (integer n = 0; n < 32; n++)
        dut.rfinstance.regs[n] = 32'b0;
    dut.rfinstance.regs[1] = value1;
    dut.rfinstance.regs[2] = value2;
    for (integer n = 0; n < initial_pc / 4; n++)
        tick();
    dut.iminstance.memory[initial_pc / 4] = instruction;
    #1;
endtask

task automatic check(
    input string label,
    input logic [31:0] instruction,
    input logic [31:0] value1,
    input logic [31:0] value2,
    input logic [31:0] expected_rd3,
    input logic [31:0] expected_pc,
    input integer initial_pc = 0
);
    logic [31:0] expected;
    prepare(instruction, value1, value2, initial_pc);
    tick();
    if (dut.pc !== expected_pc)
        $fatal(1, "%s: PC=%h expected=%h", label, dut.pc, expected_pc);
    for (integer n = 1; n < 32; n++) begin
        case (n)
            1: expected = value1;
            2: expected = value2;
            3: expected = expected_rd3;
            default: expected = 32'b0;
        endcase
        if (dut.rfinstance.regs[n] !== expected)
            $fatal(1, "%s: x%0d=%h expected=%h", label, n, dut.rfinstance.regs[n], expected);
    end
    for (integer n = 0; n < 256; n++)
        if (dut.dminstance.memory[n] !== memory_seed(n))
            $fatal(1, "%s: unexpected write to memory[%0d]", label, n);
    passed++;
endtask

task automatic check_store(
    input logic [31:0] instruction,
    input logic [31:0] base,
    input logic [31:0] data,
    input integer byte_address
);
    logic [31:0] expected;
    prepare(instruction, base, data);
    tick();
    if (dut.pc !== 32'd4)
        $fatal(1, "SW: PC=%h expected=00000004", dut.pc);
    for (integer n = 1; n < 32; n++) begin
        case (n)
            1: expected = base;
            2: expected = data;
            default: expected = 32'b0;
        endcase
        if (dut.rfinstance.regs[n] !== expected)
            $fatal(1, "SW: unexpected change to x%0d", n);
    end
    for (integer n = 0; n < 256; n++) begin
        expected = (n == byte_address / 4) ? data : memory_seed(n);
        if (dut.dminstance.memory[n] !== expected)
            $fatal(1, "SW: memory[%0d]=%h expected=%h", n, dut.dminstance.memory[n], expected);
    end
    passed++;
endtask

